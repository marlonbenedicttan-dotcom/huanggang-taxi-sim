import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1500, height: 950 } });
p.on("pageerror", e => console.log("ERR", e.message));
await p.goto("http://localhost:8010/?t=40&play=0&tour=0", { waitUntil: "networkidle" });
await p.waitForTimeout(3000);
const cam = () => p.evaluate(() => ({ ...window.__sim.scene.cam }));
console.log("start ", JSON.stringify(await cam()));
await p.mouse.move(900, 450); await p.mouse.down();
await p.mouse.move(760, 430, { steps: 12 }); await p.mouse.up();
await p.waitForTimeout(120);
console.log("drag1 ", JSON.stringify(await cam()));
await p.waitForTimeout(500);
console.log("glide ", JSON.stringify(await cam()));
await p.mouse.move(900, 450); await p.mouse.down();
await p.mouse.move(1000, 500, { steps: 10 }); await p.mouse.up();
await p.waitForTimeout(600);
console.log("drag2 ", JSON.stringify(await cam()));
await p.screenshot({ path: "/tmp/drag2.png" });
await b.close();
